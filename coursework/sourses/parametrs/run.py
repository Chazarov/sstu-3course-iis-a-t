# Функция для преобразования строки в CamelCase без пробелов и знаков
def to_camel_case(text):
    # Удаляем все, кроме букв и цифр, и преобразуем в CamelCase
    cleaned = re.sub(r'[^a-zA-Z0-9А-Яa-я]', '', text)
    if not cleaned:
        return ""
    return cleaned[0].upper() + cleaned[1:].lower()

# Создание файлов в текущей директории
